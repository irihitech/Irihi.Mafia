namespace Irihi.Mirana.Controls;

/// <summary>
/// Defines the placement of a drawer relative to the screen.
/// </summary>
public enum DrawerPlacement
{
    /// <summary>
    /// The drawer slides in from the bottom of the screen.
    /// </summary>
    Bottom,
    
    /// <summary>
    /// The drawer slides in from the top of the screen.
    /// </summary>
    Top,
    
    /// <summary>
    /// The drawer slides in from the left of the screen.
    /// </summary>
    Left,
    
    /// <summary>
    /// The drawer slides in from the right of the screen.
    /// </summary>
    Right
}
